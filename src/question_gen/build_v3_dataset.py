"""Build the v3 fine-tuning dataset: reasoning-style verification questions, self-distilled.

The fine-tune arc so far: v1 trained on EduQG (mostly multiple-choice) and collapsed into degenerate
stems; v2 trained on SQuAD (open-ended but factual) and fixed the degeneracy while learning a factual
style that the discrimination simulation only partly rewards. The diagnosis both runs support is that
the training data's format dominates. So v3 trains on data in exactly the format the task needs:
verification questions that force a student to reconstruct their own reasoning, generated by the
pipeline's own prompt.

The teacher is the local Llama 3.1 8B through Ollama, running the same claim-extraction and
question-writing prompts as the production pipeline (`generate_questions.py`). For each essay it
extracts claims with their source sentences, writes reasoning-style questions per claim, gates them
for well-formedness (garbage teachers make garbage students), and stores one training pair per
question: passage = the claim plus its source sentences (what the model sees at inference), target =
the question. Llama 3.1's licence permits using its outputs to improve other models, which is why the
teacher is local rather than a commercial API.

Contamination guard: the evaluation essays (the 14 balanced-comparison essays, which include the six
behind the fixed 18-claim set, plus the 3108a pilot) are excluded from training.

Resumable per essay; stops once the target pair count is reached.

    python src/question_gen/build_v3_dataset.py --target 2600
"""

from __future__ import annotations

import argparse
import json
import random
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
AI_DIR = REPO / "data" / "processed" / "ai_essays"
BATCH = REPO / "outputs" / "backend_comparison_batch.json"
OUT = REPO / "data" / "interim" / "qg_v3_pairs.json"
sys.path.insert(0, str(REPO / "src" / "question_gen"))
sys.path.insert(0, str(REPO / "src" / "detection"))

SEED = 42


def eval_essay_ids() -> set[str]:
    ids = {"3108a"}
    if BATCH.exists():
        ids |= set(json.loads(BATCH.read_text(encoding="utf-8")).get("balanced", {}).get("essays", []))
    return ids


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", type=int, default=2600, help="stop once this many pairs exist")
    ap.add_argument("--claims", type=int, default=3)
    args = ap.parse_args()

    from generate_questions import OllamaBackend, sentences, extract_claims, questions_for_claim
    from text_normalize import normalize_text
    from wellformed import well_formed

    excluded = eval_essay_ids()
    all_ids = sorted(p.stem for p in AI_DIR.glob("*.txt") if p.stem not in excluded)
    rng = random.Random(SEED)
    rng.shuffle(all_ids)
    print(f"{len(all_ids)} candidate essays ({len(excluded)} evaluation essays excluded)", flush=True)

    state = json.loads(OUT.read_text(encoding="utf-8")) if OUT.exists() else {"pairs": [], "done": []}
    done = set(state["done"])
    be = OllamaBackend("llama3.1:8b")
    t0 = time.time()

    for eid in all_ids:
        if len(state["pairs"]) >= args.target:
            break
        if eid in done:
            continue
        try:
            text = (AI_DIR / f"{eid}.txt").read_text(encoding="utf-8", errors="ignore")
            sents = sentences(normalize_text(text))
            claims = extract_claims(sents, be, args.claims)
            n_new = 0
            for c in claims:
                src = " ".join(s["text"] for s in c["source_sentences"])
                passage = f"Claim: {c['claim']}\nSource sentences from the essay: {src}"
                try:
                    qs = questions_for_claim(c["claim"], src, be, k=3)
                except Exception as ex:
                    print(f"    {eid} question gen failed: {type(ex).__name__}", flush=True)
                    continue
                for q in qs:
                    if well_formed(q):
                        state["pairs"].append({"passage": passage[:1500], "question": q})
                        n_new += 1
        except Exception as ex:
            print(f"  {eid} FAILED: {type(ex).__name__}: {str(ex)[:120]}", flush=True)
            n_new = 0
        state["done"].append(eid)
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(json.dumps(state), encoding="utf-8")
        rate = len(state["pairs"]) / max((time.time() - t0) / 3600, 1e-9)
        print(f"  {eid}: +{n_new} pairs, total {len(state['pairs'])}/{args.target} "
              f"({rate:.0f}/h)", flush=True)

    print(f"\nDone: {len(state['pairs'])} pairs from {len(state['done'])} essays -> {OUT}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
